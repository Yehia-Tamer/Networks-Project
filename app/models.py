from sqlalchemy import (Column, Integer, String, Text, Boolean, DateTime,
                        ForeignKey, UniqueConstraint, Index, func)
from sqlalchemy.orm import relationship
from app.database import Base


class User(Base):
    __tablename__ = "users"
    user_id = Column(Integer, primary_key=True)
    username = Column(String(50), nullable=False, unique=True)
    email = Column(String(255), nullable=False, unique=True)
    hashed_password = Column(String, nullable=False)
    display_name = Column(String(100))
    created_at = Column(DateTime(timezone=True), nullable=False, server_default=func.now())
    last_seen_at = Column(DateTime(timezone=True))  # updated when the user disconnects

    messages = relationship("Message", back_populates="sender")
    memberships = relationship("GroupMember", back_populates="user", cascade="all, delete-orphan")
    # Shortcut: user.groups -> list of Group objects (read-only, goes through group_members)
    groups = relationship("Group", secondary="group_members", viewonly=True)


class Group(Base):
    """A chat. Group chat: is_direct=False. 1-to-1 chat: is_direct=True with exactly 2 members."""
    __tablename__ = "groups"
    group_id = Column(Integer, primary_key=True)
    name = Column(String(100))                 # can be empty for direct chats
    description = Column(Text)
    is_direct = Column(Boolean, nullable=False, default=False)
    created_by = Column(Integer, ForeignKey("users.user_id", ondelete="SET NULL"))
    created_at = Column(DateTime(timezone=True), nullable=False, server_default=func.now())

    members = relationship("GroupMember", back_populates="group", cascade="all, delete-orphan")
    users = relationship("User", secondary="group_members", viewonly=True)
    messages = relationship("Message", back_populates="group", cascade="all, delete-orphan",
                            order_by="Message.message_id")


class GroupMember(Base):
    """Membership table: links users <-> groups (many-to-many)."""
    __tablename__ = "group_members"
    group_id = Column(Integer, ForeignKey("groups.group_id", ondelete="CASCADE"), primary_key=True)
    user_id = Column(Integer, ForeignKey("users.user_id", ondelete="CASCADE"), primary_key=True)
    joined_at = Column(DateTime(timezone=True), nullable=False, server_default=func.now())
    last_read_message_id = Column(Integer)     # last message this user has seen in this chat

    user = relationship("User", back_populates="memberships")
    group = relationship("Group", back_populates="members")


class Message(Base):
    __tablename__ = "messages"
    message_id = Column(Integer, primary_key=True)   # always increasing -> used for sync
    group_id = Column(Integer, ForeignKey("groups.group_id", ondelete="CASCADE"), nullable=False)
    sender_id = Column(Integer, ForeignKey("users.user_id", ondelete="CASCADE"), nullable=False)
    client_msg_id = Column(String(36), nullable=False)  # UUID generated by the phone
    content = Column(Text, nullable=False)
    time_sent = Column(DateTime(timezone=True), nullable=False, server_default=func.now())

    sender = relationship("User", back_populates="messages")
    group = relationship("Group", back_populates="messages")

    __table_args__ = (
        # Same sender + same client_msg_id = same message -> reject duplicates
        UniqueConstraint("sender_id", "client_msg_id", name="uq_messages_sender_client_msg"),
        # Speeds up: SELECT ... WHERE group_id = ? AND message_id > ? (reconnect sync)
        Index("ix_messages_group_id_message_id", "group_id", "message_id"),
    )